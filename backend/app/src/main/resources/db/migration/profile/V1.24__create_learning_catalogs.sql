-- 3. MỤC TIÊU (GOAL_TAG) và LUẬT ÁP DỤNG (GOAL_TAG_RULE)
CREATE TABLE IF NOT EXISTS goal_tag (
    goal_tag_id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    VARCHAR(40) NOT NULL,
    name                    VARCHAR(120) NOT NULL,
    description             VARCHAR(300),
    requires_textbook       BOOLEAN NOT NULL DEFAULT false,
    requires_exam_province  BOOLEAN NOT NULL DEFAULT false,
    is_premium              BOOLEAN NOT NULL DEFAULT false,
    sort_order              INT NOT NULL DEFAULT 0,
    is_active               BOOLEAN NOT NULL DEFAULT true,

    CONSTRAINT uk_goal_tag_code UNIQUE (code)
);

-- track_id NULL nghĩa là môn không chia nhánh (Toán, Ngữ Văn)
CREATE TABLE IF NOT EXISTS goal_tag_rule (
    rule_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_tag_id  INT NOT NULL,
    subject_id   INT NOT NULL,
    track_id     INT,
    level_id     INT NOT NULL,

    CONSTRAINT uk_goal_tag_rule UNIQUE NULLS NOT DISTINCT (goal_tag_id, subject_id, track_id, level_id),
    CONSTRAINT fk_goal_tag_rule_tag FOREIGN KEY (goal_tag_id) REFERENCES goal_tag(goal_tag_id) ON DELETE CASCADE,
    CONSTRAINT fk_goal_tag_rule_subject FOREIGN KEY (subject_id) REFERENCES subject(subject_id),
    CONSTRAINT fk_goal_tag_rule_track FOREIGN KEY (track_id) REFERENCES subject_track(track_id) ON DELETE CASCADE,
    CONSTRAINT fk_goal_tag_rule_level FOREIGN KEY (level_id) REFERENCES education_level(level_id)
);

CREATE INDEX IF NOT EXISTS idx_goal_tag_rule_lookup ON goal_tag_rule (subject_id, level_id, track_id);

