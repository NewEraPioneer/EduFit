SELECT g.goal_tag_id, t.subject_id, t.track_id, tl.level_id
FROM goal_tag g
CROSS JOIN subject_track t
JOIN subject_track_level tl ON tl.track_id = t.track_id
JOIN education_level l ON l.level_id = tl.level_id
WHERE t.code IN ('SCI_INTEGRATED', 'SCI_PHYSICS', 'SCI_CHEMISTRY', 'ENG_ACADEMIC')
